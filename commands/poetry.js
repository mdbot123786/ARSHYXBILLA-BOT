module.exports = async function poetryCommand(sock, chatId, msg) {
    const poem = couplets[Math.floor(Math.random() * couplets.length)];
    return sock.sendMessage(chatId, { text: `🖋️ *اردو شاعری*\n\n${poem}` }, { quoted: msg });
};
