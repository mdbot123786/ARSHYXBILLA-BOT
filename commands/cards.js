function pick(type) {
  const list = variants[type] || variants.welcome;
  return list[crypto.randomInt(list.length)];
}
function cleanText(value, max = 1200) {
  return String(value || '').replace(/[\u0000-\u001f\u007f]/g, ' ').trim().slice(0, max);
}
